def card_text(card_id: str) -> tuple[str, str, str, str] | None:
    """(core_essence, light, shadow, reversed) for a placeholder card, or None if unknown."""
    if card_id in _MAJOR:
        return _MAJOR[card_id]
    suit, _, rank = card_id.partition("-")
    if suit in _SUITS and rank in _RANKS:
        _, domain = _SUITS[suit]
        essence, light, shadow, reversed_ = _RANKS[rank]
        return essence.format(s=domain), light, shadow, reversed_
    return None
